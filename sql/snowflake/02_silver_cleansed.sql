/* =============================================================================
   ATLAS BI Platform | 02 - SILVER layer: typed, de-duplicated, DQ-flagged
   -----------------------------------------------------------------------------
   Dynamic tables = declarative pipelines. Snowflake refreshes them incrementally
   when RAW changes; TARGET_LAG is the freshness SLA agreed with the departments.
   Rows are never silently dropped: failing rows get DQ_STATUS = 'REJECTED' plus a
   reason, so the DQ dashboard can show exactly what was excluded and why.
   ========================================================================== */
USE ROLE FR_ATLAS_ENGINEER;
USE SCHEMA ATLAS_PROD.SILVER;

CREATE OR REPLACE DYNAMIC TABLE WORK_ORDER
  TARGET_LAG = '1 hour'
  WAREHOUSE  = WH_ATLAS_TRANSFORM
  REFRESH_MODE = INCREMENTAL
  COMMENT = 'Cleansed CMMS work orders. Grain: 1 row per work order (latest load wins).'
AS
WITH typed AS (
    SELECT
        TRIM(WORK_ORDER_ID)                                   AS WORK_ORDER_ID,
        TRIM(ASSET_ID)                                        AS ASSET_ID,
        TRIM(SITE_ID)                                         AS SITE_ID,
        NULLIF(TRIM(TECHNICIAN_ID), '')                       AS TECHNICIAN_ID,
        TRIM(FAILURE_CODE)                                    AS FAILURE_CODE,
        INITCAP(TRIM(WORK_ORDER_TYPE))                        AS WORK_ORDER_TYPE,
        UPPER(TRIM(PRIORITY))                                 AS PRIORITY,
        TRY_TO_TIMESTAMP_NTZ(CREATED_TS,   'YYYY-MM-DD HH24:MI:SS') AS CREATED_TS,
        TRY_TO_TIMESTAMP_NTZ(STARTED_TS,   'YYYY-MM-DD HH24:MI:SS') AS STARTED_TS,
        TRY_TO_TIMESTAMP_NTZ(COMPLETED_TS, 'YYYY-MM-DD HH24:MI:SS') AS COMPLETED_TS,
        INITCAP(TRIM(STATUS))                                 AS STATUS,
        TRY_TO_DECIMAL(LABOR_HOURS, 10, 2)                    AS LABOR_HOURS,
        TRY_TO_DECIMAL(LABOR_COST_EUR, 14, 2)                 AS LABOR_COST_EUR,
        TRY_TO_DECIMAL(MATERIAL_COST_EUR, 14, 2)              AS MATERIAL_COST_EUR,
        TRY_TO_DECIMAL(DOWNTIME_HOURS, 10, 2)                 AS DOWNTIME_HOURS,
        TRY_TO_NUMBER(SLA_TARGET_HOURS)                       AS SLA_TARGET_HOURS,
        TRY_TO_BOOLEAN(FIRST_TIME_FIX)                        AS FIRST_TIME_FIX,
        _FILE, _ROW, _LOADED_AT
    FROM ATLAS_PROD.RAW.RAW_WORK_ORDER
    QUALIFY ROW_NUMBER() OVER (PARTITION BY WORK_ORDER_ID ORDER BY _LOADED_AT DESC, _ROW DESC) = 1
)
SELECT
    t.*,
    ARRAY_COMPACT(ARRAY_CONSTRUCT(
        IFF(TECHNICIAN_ID IS NULL,                        'MISSING_TECHNICIAN', NULL),
        IFF(LABOR_HOURS IS NULL OR LABOR_HOURS <= 0,      'NON_POSITIVE_LABOR_HOURS', NULL),
        IFF(CREATED_TS IS NULL,                           'INVALID_CREATED_TS', NULL),
        IFF(STARTED_TS < CREATED_TS,                      'START_BEFORE_CREATE', NULL),
        IFF(COMPLETED_TS < STARTED_TS,                    'COMPLETE_BEFORE_START', NULL),
        IFF(WORK_ORDER_TYPE NOT IN ('Preventive','Inspection','Corrective','Emergency'), 'UNKNOWN_WO_TYPE', NULL)
    ))                                                            AS DQ_REASONS,
    IFF(ARRAY_SIZE(DQ_REASONS) = 0, 'VALID', 'REJECTED')         AS DQ_STATUS
FROM typed t;

CREATE OR REPLACE DYNAMIC TABLE ASSET
  TARGET_LAG = '1 hour' WAREHOUSE = WH_ATLAS_TRANSFORM
  COMMENT = 'Asset master with SCD2 history (VALID_FROM/VALID_TO). Source: Power Apps master data app.'
AS
SELECT
    TRY_TO_NUMBER(ASSET_SK)               AS ASSET_SK,
    ASSET_ID, ASSET_NAME, ASSET_TYPE, MANUFACTURER,
    TRY_TO_NUMBER(INSTALL_YEAR)           AS INSTALL_YEAR,
    UPPER(CRITICALITY)                    AS CRITICALITY,
    SITE_ID,
    TRY_TO_NUMBER(REPLACEMENT_VALUE_EUR)  AS REPLACEMENT_VALUE_EUR,
    TRY_TO_DATE(VALID_FROM)               AS VALID_FROM,
    TRY_TO_DATE(VALID_TO)                 AS VALID_TO,
    TRY_TO_BOOLEAN(IS_CURRENT)            AS IS_CURRENT
FROM ATLAS_PROD.RAW.RAW_ASSET
QUALIFY ROW_NUMBER() OVER (PARTITION BY ASSET_SK ORDER BY _LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE SITE
  TARGET_LAG = '1 day' WAREHOUSE = WH_ATLAS_TRANSFORM
AS
SELECT SITE_ID, SITE_NAME, CITY, REGION, COST_CENTER,
       TRY_TO_DOUBLE(LATITUDE) AS LATITUDE, TRY_TO_DOUBLE(LONGITUDE) AS LONGITUDE
FROM ATLAS_PROD.RAW.RAW_SITE
QUALIFY ROW_NUMBER() OVER (PARTITION BY SITE_ID ORDER BY _LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE TECHNICIAN
  TARGET_LAG = '1 day' WAREHOUSE = WH_ATLAS_TRANSFORM
AS
SELECT TECHNICIAN_ID, TECHNICIAN_NAME, REGION, SKILL_LEVEL,
       TRY_TO_DECIMAL(HOURLY_RATE_EUR, 8, 2) AS HOURLY_RATE_EUR,
       TRY_TO_DATE(HIRE_DATE)                AS HIRE_DATE,
       LOWER(EMAIL)                          AS EMAIL
FROM ATLAS_PROD.RAW.RAW_TECHNICIAN
QUALIFY ROW_NUMBER() OVER (PARTITION BY TECHNICIAN_ID ORDER BY _LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE FAILURE_CODE
  TARGET_LAG = '1 day' WAREHOUSE = WH_ATLAS_TRANSFORM
AS
SELECT FAILURE_CODE, FAILURE_DESCRIPTION, FAILURE_CATEGORY
FROM ATLAS_PROD.RAW.RAW_FAILURE_CODE
QUALIFY ROW_NUMBER() OVER (PARTITION BY FAILURE_CODE ORDER BY _LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE BUDGET
  TARGET_LAG = '1 day' WAREHOUSE = WH_ATLAS_TRANSFORM
AS
SELECT TRY_TO_DATE(MONTH) AS MONTH_START, SITE_ID, TRY_TO_DECIMAL(BUDGET_EUR, 14, 2) AS BUDGET_EUR
FROM ATLAS_PROD.RAW.RAW_BUDGET
QUALIFY ROW_NUMBER() OVER (PARTITION BY MONTH, SITE_ID ORDER BY _LOADED_AT DESC) = 1;
