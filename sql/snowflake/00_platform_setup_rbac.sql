/* =============================================================================
   ATLAS BI Platform | 00 - Platform setup & role-based access control (RBAC)
   Target: Snowflake            Run as: SECURITYADMIN / SYSADMIN
   -----------------------------------------------------------------------------
   Design principles
   * Functional roles (what a person does) are granted to users / Entra ID groups
     via SCIM. Access roles (what an object allows) are granted to functional roles.
     -> nobody is ever granted a privilege directly.
   * Separate DEV / TEST / PROD databases = same lifecycle stages as the
     Power BI deployment pipeline (see docs/02_governance_framework.md).
   * Medallion layers as schemas: RAW (bronze) -> SILVER -> GOLD (star schema
     consumed by Power BI). Power BI only ever reads GOLD.
   * Workload isolation: one warehouse per workload, auto-suspend 60s,
     resource monitors cap credit spend.
   ========================================================================== */

USE ROLE SYSADMIN;

-- ---------------------------------------------------------------- warehouses
CREATE WAREHOUSE IF NOT EXISTS WH_ATLAS_INGEST    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'Loading raw files / Fivetran';
CREATE WAREHOUSE IF NOT EXISTS WH_ATLAS_TRANSFORM WAREHOUSE_SIZE = SMALL  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'Dynamic tables, tasks, DQ tests';
CREATE WAREHOUSE IF NOT EXISTS WH_ATLAS_BI        WAREHOUSE_SIZE = SMALL  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
       MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 3 SCALING_POLICY = STANDARD COMMENT = 'Power BI refresh + DirectQuery';
CREATE WAREHOUSE IF NOT EXISTS WH_ATLAS_ADHOC      WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'Self-service SQL for power users';

USE ROLE ACCOUNTADMIN;
CREATE OR REPLACE RESOURCE MONITOR RM_ATLAS WITH CREDIT_QUOTA = 300 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY
           ON 90 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE WH_ATLAS_ADHOC SET RESOURCE_MONITOR = RM_ATLAS;

-- ---------------------------------------------------------------- databases (one per lifecycle stage)
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS ATLAS_DEV  COMMENT = 'Development - engineers only';
CREATE DATABASE IF NOT EXISTS ATLAS_TEST COMMENT = 'UAT with specialist departments';
CREATE DATABASE IF NOT EXISTS ATLAS_PROD COMMENT = 'Production - certified content only';
CREATE DATABASE IF NOT EXISTS ATLAS_GOVERNANCE COMMENT = 'Policies, tags, entitlements, DQ results, audit';

-- Schemas are identical in every stage, so the same scripts deploy everywhere.
-- In CI we run:  snow sql -f <script> -D "db=ATLAS_TEST"
USE DATABASE ATLAS_PROD;
CREATE SCHEMA IF NOT EXISTS RAW    WITH MANAGED ACCESS COMMENT = 'Bronze: 1:1 source copies, append-only';
CREATE SCHEMA IF NOT EXISTS SILVER WITH MANAGED ACCESS COMMENT = 'Typed, cleansed, de-duplicated, DQ-flagged';
CREATE SCHEMA IF NOT EXISTS GOLD   WITH MANAGED ACCESS COMMENT = 'Kimball star schema - the ONLY layer Power BI reads';
CREATE SCHEMA IF NOT EXISTS SANDBOX COMMENT = 'Self-service area for certified power users (auto-purged after 30 days)';

USE DATABASE ATLAS_GOVERNANCE;
CREATE SCHEMA IF NOT EXISTS POLICIES  WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS TAGS      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SECURITY  WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DQ        WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS MONITORING WITH MANAGED ACCESS;

-- ---------------------------------------------------------------- access roles (object level)
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS AR_PROD_RAW_RW;
CREATE ROLE IF NOT EXISTS AR_PROD_SILVER_RW;
CREATE ROLE IF NOT EXISTS AR_PROD_GOLD_RW;
CREATE ROLE IF NOT EXISTS AR_PROD_GOLD_RO;
CREATE ROLE IF NOT EXISTS AR_PROD_SANDBOX_RW;
CREATE ROLE IF NOT EXISTS AR_GOV_ADMIN;

GRANT USAGE ON DATABASE ATLAS_PROD TO ROLE AR_PROD_GOLD_RO;
GRANT USAGE ON SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;
GRANT SELECT ON ALL TABLES         IN SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;
GRANT SELECT ON ALL VIEWS          IN SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA ATLAS_PROD.GOLD TO ROLE AR_PROD_GOLD_RO;

GRANT ALL ON SCHEMA ATLAS_PROD.RAW     TO ROLE AR_PROD_RAW_RW;
GRANT ALL ON SCHEMA ATLAS_PROD.SILVER  TO ROLE AR_PROD_SILVER_RW;
GRANT ALL ON SCHEMA ATLAS_PROD.GOLD    TO ROLE AR_PROD_GOLD_RW;
GRANT ALL ON SCHEMA ATLAS_PROD.SANDBOX TO ROLE AR_PROD_SANDBOX_RW;
GRANT USAGE ON DATABASE ATLAS_PROD TO ROLE AR_PROD_RAW_RW;
GRANT USAGE ON DATABASE ATLAS_PROD TO ROLE AR_PROD_SILVER_RW;
GRANT USAGE ON DATABASE ATLAS_PROD TO ROLE AR_PROD_GOLD_RW;
GRANT USAGE ON DATABASE ATLAS_PROD TO ROLE AR_PROD_SANDBOX_RW;
GRANT ALL ON DATABASE ATLAS_GOVERNANCE TO ROLE AR_GOV_ADMIN;

-- ---------------------------------------------------------------- functional roles (people / services)
CREATE ROLE IF NOT EXISTS FR_ATLAS_ENGINEER     COMMENT = 'BI/data engineers: build RAW->GOLD';
CREATE ROLE IF NOT EXISTS FR_ATLAS_PBI_SERVICE  COMMENT = 'Service principal used by Power BI gateway / cloud connection';
CREATE ROLE IF NOT EXISTS FR_ATLAS_POWER_USER   COMMENT = 'Certified self-service authors (passed Level 2 training)';
CREATE ROLE IF NOT EXISTS FR_ATLAS_ANALYST_SUED COMMENT = 'Example region-scoped analyst - row access policy applies';
CREATE ROLE IF NOT EXISTS FR_ATLAS_HR_READER    COMMENT = 'May see unmasked technician PII';
CREATE ROLE IF NOT EXISTS FR_ATLAS_GOVERNANCE   COMMENT = 'BI platform owner / data governance office';

GRANT ROLE AR_PROD_RAW_RW, AR_PROD_SILVER_RW, AR_PROD_GOLD_RW TO ROLE FR_ATLAS_ENGINEER;
GRANT ROLE AR_PROD_GOLD_RO TO ROLE FR_ATLAS_PBI_SERVICE;
GRANT ROLE AR_PROD_GOLD_RO, AR_PROD_SANDBOX_RW TO ROLE FR_ATLAS_POWER_USER;
GRANT ROLE AR_PROD_GOLD_RO TO ROLE FR_ATLAS_ANALYST_SUED;
GRANT ROLE AR_PROD_GOLD_RO TO ROLE FR_ATLAS_HR_READER;
GRANT ROLE AR_GOV_ADMIN    TO ROLE FR_ATLAS_GOVERNANCE;

GRANT USAGE ON WAREHOUSE WH_ATLAS_TRANSFORM TO ROLE FR_ATLAS_ENGINEER;
GRANT USAGE ON WAREHOUSE WH_ATLAS_INGEST    TO ROLE FR_ATLAS_ENGINEER;
GRANT USAGE ON WAREHOUSE WH_ATLAS_BI        TO ROLE FR_ATLAS_PBI_SERVICE;
GRANT USAGE ON WAREHOUSE WH_ATLAS_ADHOC     TO ROLE FR_ATLAS_POWER_USER;
GRANT USAGE ON WAREHOUSE WH_ATLAS_ADHOC     TO ROLE FR_ATLAS_ANALYST_SUED;

-- Role hierarchy rolls up to SYSADMIN (Snowflake best practice: no orphan roles)
GRANT ROLE FR_ATLAS_ENGINEER, FR_ATLAS_PBI_SERVICE, FR_ATLAS_POWER_USER,
           FR_ATLAS_ANALYST_SUED, FR_ATLAS_HR_READER, FR_ATLAS_GOVERNANCE TO ROLE SYSADMIN;

-- ---------------------------------------------------------------- service user for Power BI (key-pair auth, no password)
CREATE USER IF NOT EXISTS SVC_POWERBI_ATLAS
  TYPE = SERVICE
  DEFAULT_ROLE = FR_ATLAS_PBI_SERVICE
  DEFAULT_WAREHOUSE = WH_ATLAS_BI
  COMMENT = 'Power BI semantic model refresh. Key rotated every 90 days by the platform team.';
-- ALTER USER SVC_POWERBI_ATLAS SET RSA_PUBLIC_KEY = '<public key from Key Vault>';
GRANT ROLE FR_ATLAS_PBI_SERVICE TO USER SVC_POWERBI_ATLAS;

