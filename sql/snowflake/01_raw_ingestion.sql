-- Load audit: what arrived, when, with how many errors
SELECT FILE_NAME, LAST_LOAD_TIME, ROW_COUNT, ROW_PARSED, ERROR_COUNT, STATUS
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW_WORK_ORDER',
                                           START_TIME => DATEADD(DAY, -7, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC;
