/* =============================================================================
   ATLAS BI Platform | 01 - RAW (bronze) layer: stages, file formats, ingestion
   -----------------------------------------------------------------------------
   * Sources: CMMS work-order export (CSV), asset master data (Power Apps / Azure SQL
     write-back, see sql/azure-sql), HR technician list, Controlling budget.
   * RAW tables are append-only and carry load metadata (_file, _row, _loaded_at)
     so every number in a report can be traced back to the source file (audit trail).
   ========================================================================== */
USE ROLE FR_ATLAS_ENGINEER;
USE WAREHOUSE WH_ATLAS_INGEST;
USE SCHEMA ATLAS_PROD.RAW;

CREATE OR REPLACE FILE FORMAT FF_CSV_STD
  TYPE = CSV
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL', 'null')
  EMPTY_FIELD_AS_NULL = TRUE
  ENCODING = 'UTF8'
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- External stage on Azure Blob / ADLS Gen2 (storage integration managed by platform team)
CREATE STAGE IF NOT EXISTS STG_LANDING
  URL = 'azure://helioslanding.blob.core.windows.net/atlas/'
  STORAGE_INTEGRATION = SI_AZURE_ATLAS
  FILE_FORMAT = FF_CSV_STD
  COMMENT = 'Landing zone. Folder per source system / yyyy/mm/dd.';

-- For the portfolio demo you can use an internal stage and PUT the files in /data:
--   snow stage copy data/ @ATLAS_PROD.RAW.STG_DEMO --recursive
CREATE STAGE IF NOT EXISTS STG_DEMO FILE_FORMAT = FF_CSV_STD;

-- ---------------------------------------------------------------- RAW tables (all strings -> schema-on-read in SILVER)
CREATE TABLE IF NOT EXISTS RAW_WORK_ORDER (
    WORK_ORDER_ID     VARCHAR, ASSET_ID VARCHAR, SITE_ID VARCHAR, TECHNICIAN_ID VARCHAR,
    FAILURE_CODE      VARCHAR, WORK_ORDER_TYPE VARCHAR, PRIORITY VARCHAR,
    CREATED_TS        VARCHAR, STARTED_TS VARCHAR, COMPLETED_TS VARCHAR, STATUS VARCHAR,
    LABOR_HOURS       VARCHAR, LABOR_COST_EUR VARCHAR, MATERIAL_COST_EUR VARCHAR,
    DOWNTIME_HOURS    VARCHAR, SLA_TARGET_HOURS VARCHAR, FIRST_TIME_FIX VARCHAR,
    _FILE VARCHAR, _ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS RAW_ASSET (
    ASSET_SK VARCHAR, ASSET_ID VARCHAR, ASSET_NAME VARCHAR, ASSET_TYPE VARCHAR, MANUFACTURER VARCHAR,
    INSTALL_YEAR VARCHAR, CRITICALITY VARCHAR, SITE_ID VARCHAR, REPLACEMENT_VALUE_EUR VARCHAR,
    VALID_FROM VARCHAR, VALID_TO VARCHAR, IS_CURRENT VARCHAR,
    _FILE VARCHAR, _ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS RAW_SITE (
    SITE_ID VARCHAR, SITE_NAME VARCHAR, CITY VARCHAR, REGION VARCHAR, COST_CENTER VARCHAR,
    LATITUDE VARCHAR, LONGITUDE VARCHAR,
    _FILE VARCHAR, _ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS RAW_TECHNICIAN (
    TECHNICIAN_ID VARCHAR, TECHNICIAN_NAME VARCHAR, REGION VARCHAR, SKILL_LEVEL VARCHAR,
    HOURLY_RATE_EUR VARCHAR, HIRE_DATE VARCHAR, EMAIL VARCHAR,
    _FILE VARCHAR, _ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS RAW_FAILURE_CODE (
    FAILURE_CODE VARCHAR, FAILURE_DESCRIPTION VARCHAR, FAILURE_CATEGORY VARCHAR,
    _FILE VARCHAR, _ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS RAW_BUDGET (
    MONTH VARCHAR, SITE_ID VARCHAR, BUDGET_EUR VARCHAR,
    _FILE VARCHAR, _ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE;

-- ---------------------------------------------------------------- idempotent loads (COPY skips already-loaded files)
COPY INTO RAW_WORK_ORDER
FROM (SELECT t.$1,t.$2,t.$3,t.$4,t.$5,t.$6,t.$7,t.$8,t.$9,t.$10,t.$11,t.$12,t.$13,t.$14,t.$15,t.$16,t.$17,
             METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
      FROM @STG_DEMO/fact_work_order.csv t)
ON_ERROR = ABORT_STATEMENT;

COPY INTO RAW_ASSET
FROM (SELECT t.$1,t.$2,t.$3,t.$4,t.$5,t.$6,t.$7,t.$8,t.$9,t.$10,t.$11,t.$12,
             METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
      FROM @STG_DEMO/dim_asset.csv t);

COPY INTO RAW_SITE
FROM (SELECT t.$1,t.$2,t.$3,t.$4,t.$5,t.$6,t.$7, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
      FROM @STG_DEMO/dim_site.csv t);

COPY INTO RAW_TECHNICIAN
FROM (SELECT t.$1,t.$2,t.$3,t.$4,t.$5,t.$6,t.$7, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
      FROM @STG_DEMO/dim_technician.csv t);

COPY INTO RAW_FAILURE_CODE
FROM (SELECT t.$1,t.$2,t.$3, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
      FROM @STG_DEMO/dim_failure_code.csv t);

COPY INTO RAW_BUDGET
FROM (SELECT t.$1,t.$2,t.$3, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
      FROM @STG_DEMO/fact_budget.csv t);

